"""Build the README results table straight from results/metrics/summary.csv, so no number is typed by hand."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from anomaly.config import Config

START = "<!-- results-table:start (generated by scripts/results_table.py; do not edit by hand) -->"
END = "<!-- results-table:end -->"

# Display order and names. Models missing from summary.csv are skipped.
MODEL_LABELS = {
    "baseline_random": "Random scores (sanity floor)",
    "baseline_zscore_rule": "Z-score rule",
    "isolation_forest": "Isolation Forest",
    "lstm_autoencoder_original": "LSTM autoencoder, original (bottleneck 32)",
    "lstm_autoencoder": "LSTM autoencoder, fixed (bottleneck 4)",
    "transformer": "Transformer forecaster",
    "ensemble_equal": "Ensemble, equal weights (untuned)",
    "ensemble_balanced": "Ensemble, tuned on synthetic + real (val)",
    "ensemble": "**Ensemble, tuned on synthetic (val)**",
}


def results_markdown(summary: pd.DataFrame, split: str = "test") -> str:
    """A Markdown table with one row per model: PR-AUC, event recall, and false-alarm rates on ``split``."""
    s = summary[summary["split"] == split].set_index(["model", "track"])
    lines = [
        "| Model | PR-AUC synthetic | PR-AUC real | Event recall synthetic | Event recall real "
        "| False alarms / day (all tickers) | False alarms / ticker / month |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, label in MODEL_LABELS.items():
        if (key, "synthetic") not in s.index or (key, "real") not in s.index:
            continue
        syn, real = s.loc[(key, "synthetic")], s.loc[(key, "real")]
        lines.append(
            f"| {label} | {syn.pr_auc:.3f} | {real.pr_auc:.3f} | {syn.event_recall:.3f} | {real.event_recall:.3f} "
            f"| {syn.false_alarms_per_day_all_tickers:.2f} | {syn.false_alarms_per_ticker_month:.3f} |"
        )
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """Swap the content between the START and END markers for ``block``."""
    if START not in text or END not in text:
        raise ValueError("README is missing the results-table markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


def update_readme(readme: Path, summary_csv: Path, split: str = "test") -> str:
    """Rewrite the README's generated table from ``summary_csv``. Returns the table."""
    table = results_markdown(pd.read_csv(summary_csv), split)
    readme.write_text(replace_block(readme.read_text(), table))
    return table


SCALING_START = "<!-- scaling-table:start (generated by scripts/results_table.py; do not edit by hand) -->"
SCALING_END = "<!-- scaling-table:end -->"


def _read_json(path: Path) -> dict:
    import json

    return json.loads(path.read_text()) if path.exists() else {}


def scaling_row(cfg: Config, scale: str, steps: list[dict[str, Any]], stopped: str | None) -> dict[str, Any]:
    """One row of the scaling table, read from the result files the steps wrote (missing ones become blank)."""
    r = cfg.paths.results_dir
    dl = _read_json(r / "data" / "daily_download.json")
    feat = _read_json(r / "data" / "daily_summary.json")
    stream = _read_json(r / "streaming" / "daily_replay.json")
    ens = _read_json(r / "models" / "ensembles.json").get("ensembles", {}).get("ensemble", {})
    secs = {s["step"]: s["seconds"] for s in steps}
    rss = [s["peak_rss_mb"] for s in steps if s.get("peak_rss_mb") is not None]
    test = {}
    summary_csv = r / "metrics" / "summary.csv"
    if summary_csv.exists():
        s = pd.read_csv(summary_csv)
        test = {f"{m}_{t}": s[(s.model == m) & (s.split == "test") & (s.track == t)].pr_auc.iloc[0]
                for m in ("ensemble", "baseline_zscore_rule") for t in ("synthetic", "real")
                if ((s.model == m) & (s.split == "test") & (s.track == t)).any()}
    assets = feat.get("assets", {})
    lat = stream.get("deployed_latency_us", {})
    syn = stream.get("metrics", {}).get("synthetic", {})
    return {
        "scale": scale,
        "universe_file": cfg.universe.file.name,
        "completed": stopped is None,
        "stopped_at": stopped or "",
        "tickers_requested": dl.get("requested", 0) - 1 if dl else None,  # minus the market ticker
        "tickers_newly_downloaded": dl.get("downloaded"),
        "tickers_failed_download": dl.get("failed"),
        "tickers_passed_cleaning": assets.get("passed_cleaning"),
        "feature_rows": feat.get("rows", {}).get("total"),
        "download_seconds": secs.get("download"),
        "features_seconds": secs.get("features"),
        "labels_seconds": secs.get("labels"),
        "train_seconds": secs.get("train"),
        "ensemble_seconds": secs.get("ensemble"),
        "stream_seconds": secs.get("stream"),
        "total_seconds": round(sum(secs.values()), 1),
        "peak_rss_mb": max(rss) if rss else None,
        "ensemble_weights": ", ".join(f"{k} {v:g}" for k, v in ens.get("weights", {}).items()) if ens else "",
        "stream_bars": stream.get("bars_timed"),
        "latency_p50_us": lat.get("p50_us"),
        "latency_p95_us": lat.get("p95_us"),
        "latency_p99_us": lat.get("p99_us"),
        "false_alarms_per_day_all_tickers": syn.get("false_alarms_per_day_all_tickers"),
        "false_alarms_per_ticker_month": syn.get("false_alarms_per_ticker_month"),
        "test_pr_auc_synthetic": test.get("ensemble_synthetic"),
        "test_pr_auc_real": test.get("ensemble_real"),
        "rule_test_pr_auc_synthetic": test.get("baseline_zscore_rule_synthetic"),
        "rule_test_pr_auc_real": test.get("baseline_zscore_rule_real"),
    }


def _fmt(value: Any, spec: str = ",.0f") -> str:
    if value is None or (isinstance(value, float) and np.isnan(value)) or value == "":
        return "–"
    return format(value, spec)


def scaling_markdown(table: pd.DataFrame) -> str:
    """The README scaling table: what each scale handled, how long it took, and how the deployed ensemble did."""
    names = {"100": "100 stocks", "sp500": "S&P 500", "us_all": "All US-listed"}
    lines = [
        "| | " + " | ".join(names.get(str(s), str(s)) for s in table["scale"]) + " |",
        "|---|" + "---|" * len(table),
    ]
    rows = [
        ("Tickers requested", "tickers_requested", ",.0f"),
        ("Newly downloaded (others were cached)", "tickers_newly_downloaded", ",.0f"),
        ("Failed to download", "tickers_failed_download", ",.0f"),
        ("**Passed cleaning (assets handled)**", "tickers_passed_cleaning", ",.0f"),
        ("Feature rows (daily bars)", "feature_rows", ",.0f"),
        ("Download time (s)", "download_seconds", ",.0f"),
        ("Clean + features time (s)", "features_seconds", ",.0f"),
        ("Labels time, incl. earnings dates (s)", "labels_seconds", ",.0f"),
        ("LSTM training time (s)", "train_seconds", ",.0f"),
        ("Ensemble tuning time (s)", "ensemble_seconds", ",.0f"),
        ("Streaming replay time (s)", "stream_seconds", ",.0f"),
        ("**Total pipeline time (min)**", "total_minutes", ",.1f"),
        ("Peak memory of any step (GB)", "peak_gb", ",.1f"),
        ("Ensemble weights (tuned on val)", "ensemble_weights", ""),
        ("Bars replayed in the stream", "stream_bars", ",.0f"),
        ("**Latency p50 / p95 / p99 (µs per bar)**", "latency", ""),
        ("False alarms per day (all tickers)", "false_alarms_per_day_all_tickers", ".2f"),
        ("**False alarms per ticker per month**", "false_alarms_per_ticker_month", ".3f"),
        ("Test PR-AUC synthetic / real", "pr_auc", ""),
        ("Completed", "status", ""),
    ]
    t = table.copy()
    t["total_minutes"] = t["total_seconds"] / 60
    t["peak_gb"] = t["peak_rss_mb"] / 1000
    t["latency"] = [f"{_fmt(a)} / {_fmt(b)} / {_fmt(c)}" for a, b, c in zip(t.latency_p50_us, t.latency_p95_us, t.latency_p99_us)]
    t["pr_auc"] = [f"{_fmt(a, '.3f')} / {_fmt(b, '.3f')}" for a, b in zip(t.test_pr_auc_synthetic, t.test_pr_auc_real)]
    t["status"] = ["yes" if c else f"stopped: {s}" for c, s in zip(t["completed"], t["stopped_at"].fillna(""))]
    for label, col, spec in rows:
        cells = [str(v) if not spec else _fmt(v if pd.notna(v) else None, spec) for v in t[col]]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def update_readme_scaling(readme: Path, table_csv: Path) -> str | None:
    """Rewrite the README scaling table from ``table_csv`` (no-op if there's no table yet)."""
    if not table_csv.exists():
        return None
    md = scaling_markdown(pd.read_csv(table_csv, dtype={"scale": str}))
    text = readme.read_text()
    if SCALING_START not in text or SCALING_END not in text:
        raise ValueError("README is missing the scaling-table markers")
    head, rest = text.split(SCALING_START, 1)
    _, tail = rest.split(SCALING_END, 1)
    readme.write_text(f"{head}{SCALING_START}\n{md}\n{SCALING_END}{tail}")
    return md
